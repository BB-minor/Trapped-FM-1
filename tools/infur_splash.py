"""The INFUR boot splash for the FM-1.

Builds the mark + wordmark lockup from assets/infur/ and emits the same RLE the
firmware's splash.c reads (16-colour palette, byte = (run - 1) << 4 | index).

  tools/infur_splash.py OUT.h        write the header (replaces sloop_logo.h)
  tools/infur_splash.py --measure    report the byte cost only

Unlike the SLOOP logo the canvas is cropped to the lockup (240 x 62): splash.c
takes its width and height from the header, so a tighter canvas simply costs
fewer bytes. Index 0 is never drawn by splash.c, so the ground is index 1.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MARK = ROOT / "assets/infur/mark-128.png"
WORD = ROOT / "assets/infur/wordmark-dark.webp"

W = 240
MARK_H, WORD_H, GAP = 52, 38, 14
GROUND, SAGE, BONE = (0x11, 0x15, 0x12), (0x79, 0xA3, 0x94), (0xEC, 0xE6, 0xD8)
PAL = [(0, 0, 0), GROUND, SAGE, BONE]          # 0 unused (splash.c skips it)


def rgb565(c):
    return ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)


def mask(path, h):
    """the artwork's own alpha, as a 1-bit mask of height h, cropped tight"""
    a = Image.open(path).convert("RGBA").split()[3].point(lambda v: 255 if v > 110 else 0)
    a = a.crop(a.getbbox())
    w = max(1, round(a.width * h / a.height))
    return a.resize((w, h), Image.LANCZOS).point(lambda v: 255 if v > 110 else 0)


def lockup():
    m, w = mask(MARK, MARK_H), mask(WORD, WORD_H)
    gap = GAP
    total = m.width + gap + w.width
    if total > W - 12:                                   # keep a margin
        k = (W - 12) / total
        m, w = mask(MARK, round(MARK_H * k)), mask(WORD, round(WORD_H * k))
        gap = max(6, round(gap * k))
        total = m.width + gap + w.width
    h = max(m.height, w.height) + 10
    idx = [1] * (W * h)                                  # ground
    x = (W - total) // 2
    for src, colour, ox in ((m, 2, x), (w, 3, x + m.width + gap)):
        oy = (h - src.height) // 2
        px = src.load()
        for yy in range(src.height):
            for xx in range(src.width):
                if px[xx, yy]:
                    idx[(oy + yy) * W + ox + xx] = colour
    return idx, W, h


def encode(idx):
    out = bytearray()
    i, n = 0, len(idx)
    while i < n:
        j = i
        while j < n and idx[j] == idx[i] and j - i < 16:
            j += 1
        out.append(((j - i - 1) << 4) | idx[i])
        i = j
    return out


def main():
    idx, w, h = lockup()
    rle = encode(idx)
    if "--measure" in sys.argv:
        print(f"infur splash {w}x{h}: {len(rle)} B RLE "
              f"(SLOOP's logo was 4635 B: {4635 - len(rle):+d})")
        return
    pal = PAL + [(0, 0, 0)] * (16 - len(PAL))
    L = ["/* generated by tools/infur_splash.py: the INFUR boot splash */", "#pragma once",
         "#include <stdint.h>", f"#define SLOOP_SPLASH_W {w}", f"#define SLOOP_SPLASH_H {h}",
         "static const uint16_t SLOOP_SPLASH_PAL[16] = {"
         + ", ".join(f"0x{rgb565(c):04X}" for c in pal) + "};",
         f"static const uint8_t SLOOP_SPLASH_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(sys.argv[1]).write_text("\n".join(L) + "\n")
    print(f"infur splash {w}x{h}, {len(rle)} B RLE -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
